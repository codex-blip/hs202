export function resolveLanguageCode(value: string | undefined): LanguageCode | undefined {
  if (!value) return undefined;
  const normalized = value.trim().toLowerCase();
  const code = normalized.split(/[-_]/, 1)[0];
  const matchingLanguage = languages.find((language) => language.code === code);
  return matchingLanguage?.code ?? languageAliases[normalized];
}

