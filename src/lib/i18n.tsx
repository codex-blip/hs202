const dictionaries: Record<UiLanguageCode, typeof en> = { en, hi, pa };

type I18nContextValue = {
  lang: UiLanguageCode;
  setLang: (l: UiLanguageCode) => void;
  t: (key: keyof typeof en) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<UiLanguageCode>('en');
  const t = (key: keyof typeof en) => dictionaries[lang][key] ?? en[key];
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useLanguage(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useLanguage must be used inside LanguageProvider');
  return ctx;
}

